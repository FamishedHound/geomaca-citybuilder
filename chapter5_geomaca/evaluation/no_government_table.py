"""Table 5.5: CityBuilder without a government.

Columns: the Heuristic column of Table 5.2 (from the CityBuilder evaluation
record), the No-government protocol run, and the paired difference (No
government minus Heuristic on identical developer plans and random numbers;
mean +- SE across the five replicates, paired t-test markers).

Usage::

    python -m chapter5_geomaca.evaluation.no_government_table \\
        --eval <citybuilder_evaluation.json> --nogov <no_government_evaluation.json> --out <dir>

Writes ``citybuilder_no_government_table.tex``.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

from .tables import PILLAR_GROUPS, fmt, mean_, se_, sig

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_EVAL = PACKAGE_ROOT / "results" / "evaluation" / "citybuilder_evaluation.json"
DEFAULT_NOGOV = PACKAGE_ROOT / "results" / "evaluation" / "no_government_evaluation.json"
DEFAULT_OUT = PACKAGE_ROOT / "results" / "tables"

ROW_LABELS = {
    "gdp": "GDP (\\$M $\\uparrow$)",
    "tax_revenue": "Tax Revenue (\\$M $\\uparrow$)",
    "developer_profit": "Developer Profit (\\$M $\\uparrow$)",
    "green_ratio": "Green ratio (\\% $\\uparrow$)",
    "woodland_ratio": "Woodland ratio (\\% $\\uparrow$)",
    "density": "Density (\\% $\\downarrow$)",
    "population": "Population $\\uparrow$",
    "segregation": "Segregation $\\downarrow$",
    "qol": "Quality of Life $\\uparrow$",
}
CELL_STYLE = {
    "gdp": "money_M", "tax_revenue": "money_M", "developer_profit": "money_M",
    "green_ratio": "pct", "woodland_ratio": "pct", "density": "pct",
    "population": "int", "segregation": "f3", "qol": "f3",
}
# (scale, decimals of the mean, decimals of the SE) of the paired-difference column
DIFF_STYLE = {
    "gdp": (1e-6, 2, 2), "tax_revenue": (1e-6, 2, 2), "developer_profit": (1e-6, 2, 2),
    "green_ratio": (100.0, 2, 2), "woodland_ratio": (100.0, 2, 2), "density": (100.0, 2, 2),
    "population": (1.0, 1, 2), "segregation": (1.0, 4, 4), "qol": (1.0, 3, 3),
}
CONTRAST = "no_government_minus_heuristic"
IDENTICAL_NAMES = {"woodland_ratio": "Woodland", "density": "Density"}


def diff_cell(key: str, rep: Dict, episode_level: Dict) -> str:
    """Paired difference cell: '$0$' when the arms are identical in every paired episode."""
    if episode_level.get("n_exactly_zero") == episode_level.get("n") and rep.get("t") is None:
        return "$0$"
    scale, dm, ds = DIFF_STYLE[key]
    mark = sig(rep["p_ttest"]) if rep.get("p_ttest") is not None else ""
    return (f"${rep['mean_diff'] * scale:.{dm}f}${{\\scriptsize$\\pm${rep['se_diff'] * scale:.{ds}f}}}"
            + mark)


def table_tex(evaluation: Dict, nogov: Dict, n_eval: int) -> str:
    heur = evaluation["methods"]["heuristic"]["summary"]
    prot = nogov["protocol_run"]["summary"]
    contrast = nogov["paired"]["contrasts"][CONTRAST]["metrics"]
    n_rep = len(nogov["protocol_run"]["per_replicate"])
    marks = sorted({sig(contrast[k]["replicate_level_n5"]["p_ttest"])
                    for k in contrast if contrast[k]["replicate_level_n5"].get("p_ttest") is not None}
                   - {""}, key=len)
    legend = {"$^{*}$": "$^{*}p<0.05$", "$^{**}$": "$^{**}p<0.01$",
              "$^{***}$": "$^{***}p<10^{-3}$", "$^{****}$": "$^{****}p<10^{-4}$"}
    identical = [IDENTICAL_NAMES[k] for k in ("woodland_ratio", "density")
                 if diff_cell(k, contrast[k]["replicate_level_n5"], contrast[k]["episode_level_n250"]) == "$0$"]
    rows: List[str] = [
        "% Table 5.5 -- generated by chapter5_geomaca.evaluation.no_government_table",
        "\\begin{table}[t]",
        "\\centering\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{CityBuilder without a government. The Heuristic and No government columns use "
        "the protocol of Tab.~\\ref{tab:p3-main} (uniform-random developer, "
        f"${n_rep}$ replicates of ${n_eval}$ episodes) and give mean $\\pm$ SE across replicates; "
        "the Heuristic column repeats Tab.~\\ref{tab:p3-main}. The last column is the mean "
        "difference, No government minus Heuristic, when both are run on the same developer plans "
        "and random numbers in every episode, $\\pm$ SE across the five replicates; paired "
        "$t$-tests: " + ", ".join(legend[m] for m in marks) + "."
        + (" " + " and ".join(identical) + " are identical in every paired episode." if identical else "")
        + "}",
        "\\label{tab:p3-nogov}",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "\\textbf{Pillar} & \\textbf{Metric} & \\textbf{Heuristic} & \\textbf{No government} & "
        "\\textbf{Paired difference} \\\\",
        "\\midrule",
    ]
    for gi, (pillar, keys) in enumerate(PILLAR_GROUPS):
        for ri, key in enumerate(keys):
            h = heur[key]["values"]
            n = prot[key]["values"]
            cells = [fmt(mean_(h), se_(h), CELL_STYLE[key]), fmt(mean_(n), se_(n), CELL_STYLE[key]),
                     diff_cell(key, contrast[key]["replicate_level_n5"],
                               contrast[key]["episode_level_n250"])]
            pillar_cell = f"\\multirow{{{len(keys)}}}{{*}}{{\\textbf{{{pillar}}}}}" if ri == 0 else ""
            rows.append(f"{pillar_cell} & {ROW_LABELS[key]} & " + " & ".join(cells) + " \\\\")
        if gi < len(PILLAR_GROUPS) - 1:
            rows.append("\\midrule")
    rows += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(rows) + "\n"


def write(eval_path: Path, nogov_path: Path, out_dir: Path) -> Path:
    evaluation = json.loads(Path(eval_path).read_text(encoding="utf-8"))
    nogov = json.loads(Path(nogov_path).read_text(encoding="utf-8"))
    n_eval = int(nogov.get("n_eval_per_replicate", evaluation.get("n_eval_per_replicate", 50)))
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "citybuilder_no_government_table.tex"
    path.write_text(table_tex(evaluation, nogov, n_eval), encoding="utf-8")
    return path


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--eval", type=str, default=str(DEFAULT_EVAL))
    ap.add_argument("--nogov", type=str, default=str(DEFAULT_NOGOV))
    ap.add_argument("--out", type=str, default=str(DEFAULT_OUT))
    args = ap.parse_args(argv)
    print(f"Wrote {write(Path(args.eval), Path(args.nogov), Path(args.out))}")


if __name__ == "__main__":
    main()
